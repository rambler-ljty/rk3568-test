#include <stdio.h>      // 标准输入输出函数（printf等）
#include <sys/types.h>  // 基本系统数据类型定义
#include <sys/stat.h>   // 文件状态结构体定义
#include <fcntl.h>      // 文件控制定义（open等）
#include <unistd.h>     // UNIX标准函数定义（read、close等）

/**
 * ds18b20_get_temp - DS18B20温度数据解析和显示函数
 * @value: 从内核驱动读取的16位原始温度数据
 * 功能：解析DS18B20的16位温度数据，提取符号位，转换为实际温度值并显示
 * 
 * DS18B20温度数据格式说明：
 * - 16位数据：包含符号位和温度值
 * - 符号位：第11位（bit11）表示温度正负
 *   - bit11 = 0：正温度
 *   - bit11 = 1：负温度
 * - 温度值：低11位（bit0-bit10）表示温度数值
 * - 分辨率：0.0625°C（1/16°C）
 * - 温度范围：-55°C到+125°C
 * 
 * 温度转换公式：实际温度 = 原始值 × 0.0625
 */
void ds18b20_get_temp(int value){

	char sig;      // 温度符号字符（'+' 或 '-'）
	float temp;    // 转换后的实际温度值（浮点数）

	// 1. 检查第11位（bit11）判断温度正负
	// (value >> 11) & 0x01：将数据右移11位，然后与0x01进行位与操作
	// 如果bit11为1，结果为1，表示负温度；如果bit11为0，结果为0，表示正温度
	if((value >> 11) & 0x01){
		// 负温度处理
		sig='-';                    // 设置符号为负号
		
		// 对负值进行二进制补码转换
		// ~value：按位取反
		// +1：加1，完成补码转换
		value=~value+1;
		
		// 清除高5位（bit11-bit15），只保留低11位温度值
		// 0xF8 << 8：将0xF8左移8位，得到0xF800
		// ~(0xF8 << 8)：按位取反，得到0x07FF
		// value & 0x07FF：只保留低11位，清除高5位
		value &= ~(0xF8 <<8);
	
	}else{
		// 正温度处理
		sig='+';  // 设置符号为正号
	}

	// 2. 将原始温度值转换为实际温度
	// 0.0625 = 1/16，这是DS18B20的温度分辨率
	temp=value*0.0625;
	
	// 3. 显示温度值，包含符号和精确到小数点后4位的温度值
	// %c：显示符号字符（+ 或 -）
	// %.4f：显示浮点数，保留4位小数
	printf("温度为 %c%.4f",sig,temp);
}

/**
 * main - 主函数
 * @argc: 命令行参数个数
 * @argv: 命令行参数数组
 * 功能：程序入口点，负责打开设备文件、循环读取温度数据并显示
 * 返回值：0表示成功，-1表示失败
 */
int main(int argc,char *argv[]){
	int fd;    // 文件描述符，用于操作设备文件
	int data;  // 存储从设备读取的温度数据

	// 1. 打开DS18B20设备文件
	// "/dev/ds18b20"：设备节点路径，由内核驱动创建
	// O_RDWR：以读写模式打开文件
	// 返回值：成功返回文件描述符，失败返回-1
	fd=open("/dev/ds18b20",O_RDWR);
	if(fd<0){
		printf("open fold failed!\n");  // 打开设备文件失败
		return -1;                      // 返回错误码
	}

	// 2. 进入无限循环，持续读取温度数据
	while(1){
	
		// 从设备文件读取温度数据
		// read(fd,&data,sizeof(data))：从文件描述符fd读取数据到data变量
		// sizeof(data)：读取的字节数（4字节，int类型）
		// 返回值：成功返回读取的字节数，失败返回-1
		if(read(fd,&data,sizeof(data))<0){
			printf("open data failed! \n");  // 读取数据失败
			return -1;                       // 返回错误码
		}

		// 调用温度解析函数，显示温度值
		ds18b20_get_temp(data);
	}

	// 3. 关闭设备文件（实际上由于无限循环，这行代码不会被执行）
	close(fd);
	return 0;  // 程序正常结束
}

